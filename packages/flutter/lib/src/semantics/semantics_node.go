// maxFrameworkAccessibilityIdentifier is the maximal semantic node
// identifier generated by the framework: the least significant 16 bits are
// reserved for framework generated ids, the most significant 32 bits for
// engine generated ids.
const maxFrameworkAccessibilityIdentifier = (1 << 16) - 1

var lastIdentifier = 0

func generateNewID() int {
	lastIdentifier = (lastIdentifier + 1) % maxFrameworkAccessibilityIdentifier
	return lastIdentifier
}

// SemanticsNode is a node that represents some semantic data. The semantics
// tree is maintained during the semantics phase of the pipeline and
// reflects what the accessibility services see. Use it by pointer.
type SemanticsNode struct {
	foundation.DiagnosticableTreeMixin

	// Key uniquely identifies this node in the list of sibling nodes (nil:
	// none).
	Key foundation.Key

	id           int
	showOnScreen func()

	transform               *vm.Matrix4
	traversalChildTransform *vm.Matrix4
	rect                    ui.Rect

	// ParentSemanticsClipRect is the semantic clip from an ancestor that
	// was applied to this node (nil: none).
	ParentSemanticsClipRect *ui.Rect
	// ParentPaintClipRect is the paint clip from an ancestor that was
	// applied to this node (nil: none).
	ParentPaintClipRect *ui.Rect
	// IndexInParent is the index of this node within the parent's list of
	// semantic children that count for scrolling (nil: not one).
	IndexInParent *int

	isMergedIntoParent              bool
	areUserActionsBlocked           bool
	mergeAllDescendantsIntoThisNode bool

	children              []*SemanticsNode // nil: Dart's null
	debugPreviousSnapshot []*SemanticsNode
	dead                  bool

	owner           *SemanticsOwner
	parent          *SemanticsNode
	traversalParent *SemanticsNode
	depth           int
	locale          *ui.Locale

	dirty bool

	actions                map[ui.SemanticsAction]SemanticsActionHandler
	customSemanticsActions customActionEntries
	actionsAsBits          int

	// Tags are the tags attached to this node (nil: null; no duplicates,
	// in insertion order).
	Tags []*SemanticsTag

	flags                     ui.SemanticsFlags
	identifier                string
	traversalParentIdentifier any
	traversalChildIdentifier  any
	attributedLabel           AttributedString
	attributedValue           AttributedString
	attributedIncreasedValue  AttributedString
	attributedDecreasedValue  AttributedString
	attributedHint            AttributedString
	tooltip                   string
	hintOverrides             *SemanticsHintOverrides
	textDirection             *ui.TextDirection
	sortKey                   SemanticsSortKey
	textSelection             *services.TextSelection
	isMultiline               *bool
	scrollChildCount          *int
	scrollIndex               *int
	scrollPosition            *float64
	scrollExtentMax           *float64
	scrollExtentMin           *float64
	platformViewID            *int
	maxValueLength            *int
	currentValueLength        *int
	headingLevel              int
	linkURL                   *url.URL
	role                      ui.SemanticsRole
	controlsNodes             []string
	minValue                  *string
	maxValue                  *string
	validationResult          ui.SemanticsValidationResult
	hitTestBehavior           ui.SemanticsHitTestBehavior
	inputType                 ui.SemanticsInputType
}

// SemanticsNodeOptions are SemanticsNode's named parameters.
type SemanticsNodeOptions struct {
	Key          foundation.Key
	ShowOnScreen func()
}

func newSemanticsNode(id int, o SemanticsNodeOptions) *SemanticsNode {
	n := &SemanticsNode{Key: o.Key, id: id, showOnScreen: o.ShowOnScreen}
	n.initFromEmptyConfig()
	n.SetSelf(n)
	return n
}

// initFromEmptyConfig gives the fields their initializers (the values of
// SemanticsNode._kEmptyConfig).
func (n *SemanticsNode) initFromEmptyConfig() {
	empty := kEmptyConfig()
	n.mergeAllDescendantsIntoThisNode = empty.IsMergingSemanticsOfDescendants()
	n.actions = empty.actions
	n.customSemanticsActions = empty.customSemanticsActions
	n.actionsAsBits = empty.actionsAsBits
	n.flags = ui.SemanticsFlagsNone
	n.identifier = empty.Identifier()
	n.attributedLabel = empty.AttributedLabel()
	n.attributedValue = empty.AttributedValue()
	n.attributedIncreasedValue = empty.AttributedIncreasedValue()
	n.attributedDecreasedValue = empty.AttributedDecreasedValue()
	n.attributedHint = empty.AttributedHint()
	n.tooltip = empty.Tooltip()
	n.textDirection = empty.TextDirection()
	n.headingLevel = empty.headingLevel
	n.linkURL = empty.linkURL
	n.role = empty.Role()
	n.controlsNodes = empty.ControlsNodes()
	n.validationResult = empty.ValidationResult()
	n.hitTestBehavior = ui.SemanticsHitTestBehaviorDefer
	n.inputType = empty.InputType()
}

// NewSemanticsNode is SemanticsNode({key, showOnScreen}): a node with a new
// id.
func NewSemanticsNode(opts ...SemanticsNodeOptions) *SemanticsNode {
	var o SemanticsNodeOptions
	if len(opts) > 0 {
		o = opts[0]
	}
	return newSemanticsNode(generateNewID(), o)
}

// NewSemanticsNodeRoot is SemanticsNode.root({key, showOnScreen, owner}):
// the root node (id 0), attached to owner.
func NewSemanticsNodeRoot(owner *SemanticsOwner, opts ...SemanticsNodeOptions) *SemanticsNode {
	var o SemanticsNodeOptions
	if len(opts) > 0 {
		o = opts[0]
	}
	n := newSemanticsNode(0, o)
	n.Attach(owner)
	return n
}

// ID is the unique identifier for this node. The root node has an id of
// zero; other ids are allocated by the framework.
func (n *SemanticsNode) ID() int { return n.id }

// ---- GEOMETRY

// Transform is the transform from this node's coordinate system to its
// parent's (nil: identity).
func (n *SemanticsNode) Transform() *vm.Matrix4 { return n.transform }

// SetTransform sets Transform (an identity matrix is stored as nil).
func (n *SemanticsNode) SetTransform(value *vm.Matrix4) {
	if !painting.MatrixUtils.MatrixEquals(n.transform, value) {
		if value == nil || painting.MatrixUtils.IsIdentity(value) {
			n.transform = nil
		} else {
			n.transform = value
		}
		n.markDirty()
	}
}

// traversalTransform is the transform to the traversal parent (nil:
// identity).
func (n *SemanticsNode) traversalTransform() *vm.Matrix4 {
	if foundation.KIsWeb {
		return n.transform
	}
	if n.traversalChildTransform != nil {
		return n.traversalChildTransform
	}
	return n.transform
}

// Rect is the bounding box for this node in its coordinate system.
func (n *SemanticsNode) Rect() ui.Rect { return n.rect }

// SetRect sets Rect (it must be finite).
func (n *SemanticsNode) SetRect(value ui.Rect) {
	if !value.IsFinite() {
		panic(dart.NewAssertionError(n.String() + " (with " + ownerString(n.owner) + ") tried to set a non-finite rect."))
	}
	if n.rect != value {
		n.rect = value
		n.markDirty()
	}
}

func ownerString(o *SemanticsOwner) string {
	if o == nil {
		return "null"
	}
	return o.String()
}

// IsInvisible: whether the node is invisible (not merged into its parent,
// and empty or transformed to zero).
func (n *SemanticsNode) IsInvisible() bool {
	return !n.IsMergedIntoParent() && (n.Rect().IsEmpty() || (n.transform != nil && n.transform.IsZero()))
}

// ---- MERGING

// IsMergedIntoParent is whether this node merges its semantic information
// into an ancestor node.
func (n *SemanticsNode) IsMergedIntoParent() bool { return n.isMergedIntoParent }

// SetIsMergedIntoParent sets IsMergedIntoParent.
func (n *SemanticsNode) SetIsMergedIntoParent(value bool) {
	if n.isMergedIntoParent == value {
		return
	}
	n.isMergedIntoParent = value
	if n.parent != nil {
		n.parent.markDirty()
	}
}

// AreUserActionsBlocked is whether the user can interact with this node in
// assistive technologies.
func (n *SemanticsNode) AreUserActionsBlocked() bool { return n.areUserActionsBlocked }

// SetAreUserActionsBlocked sets AreUserActionsBlocked.
func (n *SemanticsNode) SetAreUserActionsBlocked(value bool) {
	if n.areUserActionsBlocked == value {
		return
	}
	n.areUserActionsBlocked = value
	n.markDirty()
}

// IsPartOfNodeMerging is whether this node is taking part in a merge of
// semantic information.
func (n *SemanticsNode) IsPartOfNodeMerging() bool {
	return n.MergeAllDescendantsIntoThisNode() || n.IsMergedIntoParent()
}

// MergeAllDescendantsIntoThisNode is whether this node and all of its
// descendants should be treated as one logical entity.
func (n *SemanticsNode) MergeAllDescendantsIntoThisNode() bool {
	return n.mergeAllDescendantsIntoThisNode
}

// ---- CHILDREN

func (n *SemanticsNode) replaceChildren(newChildren []*SemanticsNode) {
	for _, child := range newChildren {
		dartAssert(child != n, nil)
	}
	if foundation.KDebugMode {
		seenChildren := map[*SemanticsNode]bool{}
		for _, child := range newChildren {
			dartAssert(!seenChildren[child], nil) // check for duplicate adds
			seenChildren[child] = true
		}
	}

	// The goal of this function is updating sawChange.
	if n.children != nil {
		for _, child := range n.children {
			child.dead = true
		}
	}
	for _, child := range newChildren {
		child.dead = false
	}
	sawChange := false
	if n.children != nil {
		for _, child := range n.children {
			if child.dead {
				if child.Parent() == n {
					// we might have already had our child stolen from us by
					// another node that is deeper in the tree.
					n.dropChild(child)
				}
				sawChange = true
			}
		}
	}
	for _, child := range newChildren {
		if child.Parent() != n {
			if child.Parent() != nil {
				// we're rebuilding the tree from the bottom up, so it's possible
				// that our child was, in the last pass, a child of one of our
				// ancestors. In that case, we drop the child eagerly here.
				child.Parent().dropChild(child)
			}
			dartAssert(!child.Attached(), nil)
			n.adoptChild(child)
			sawChange = true
		}
	}
	// Wait until the new children are adopted so isMergedIntoParent becomes
	// up-to-date.
	if foundation.KDebugMode {
		if sameSlice(newChildren, n.children) {
			var mutationErrors []foundation.DiagnosticsNode
			if len(newChildren) != len(n.debugPreviousSnapshot) {
				mutationErrors = append(mutationErrors, foundation.NewErrorDescription(
					"The list's length has changed from "+strconv.Itoa(len(n.debugPreviousSnapshot))+
						" to "+strconv.Itoa(len(newChildren))+"."))
			} else {
				for i := range newChildren {
					if newChildren[i] != n.debugPreviousSnapshot[i] {
						if len(mutationErrors) > 0 {
							mutationErrors = append(mutationErrors, foundation.NewErrorSpacer())
						}
						singleLine := foundation.DiagnosticsTreeStyleSingleLine
						prev, next := "Previous child", "New child"
						mutationErrors = append(mutationErrors,
							foundation.NewErrorDescription("Child node at position "+strconv.Itoa(i)+" was replaced:"),
							n.debugPreviousSnapshot[i].ToDiagnosticsNodeInOrder(DebugSemanticsDumpOrderTraversalOrder,
								foundation.ToDiagnosticsNodeOptions{Name: &prev, Style: &singleLine}),
							newChildren[i].ToDiagnosticsNodeInOrder(DebugSemanticsDumpOrderTraversalOrder,
								foundation.ToDiagnosticsNodeOptions{Name: &next, Style: &singleLine}),
						)
					}
				}
			}
			if len(mutationErrors) > 0 {
				panic(foundation.NewFlutterErrorFromParts(append([]foundation.DiagnosticsNode{
					foundation.NewErrorSummary("Failed to replace child semantics nodes because the list of `SemanticsNode`s was mutated."),
					foundation.NewErrorHint("Instead of mutating the existing list, create a new list containing the desired `SemanticsNode`s."),
					foundation.NewErrorDescription("Error details:"),
				}, mutationErrors...)))
			}
		}
		n.debugPreviousSnapshot = append([]*SemanticsNode{}, newChildren...)

		ancestor := n
		for ancestor.Parent() != nil {
			ancestor = ancestor.Parent()
		}
		for _, child := range newChildren {
			dartAssert(child != ancestor, nil)
		}
	}

	if !sawChange && n.children != nil {
		dartAssert(len(newChildren) == len(n.children), nil)
		// Did the order change?
		for i := range n.children {
			if n.children[i].ID() != newChildren[i].ID() {
				sawChange = true
				break
			}
		}
	}
	n.children = newChildren
	if sawChange {
		n.markDirty()
	}
}

// sameSlice is Dart's identical() on two lists: Go slices of the same list
// share their backing array, whatever their lengths after an in-place
// append (slices without capacity can't be told apart, and are not the
// same).
func sameSlice(a, b []*SemanticsNode) bool {
	if cap(a) == 0 || cap(b) == 0 {
		return false
	}
	return &a[:1][0] == &b[:1][0]
}

// HasChildren is whether this node has a non-zero number of children.
func (n *SemanticsNode) HasChildren() bool { return len(n.children) > 0 }

// ChildrenCount is the number of children this node has.
func (n *SemanticsNode) ChildrenCount() int {
	if n.HasChildren() {
		return len(n.children)
	}
	return 0
}

// ChildrenCountInTraversalOrder is the number of children in traversal
// order.
func (n *SemanticsNode) ChildrenCountInTraversalOrder() int {
	return len(n.childrenInTraversalOrder())
}

// VisitChildren visits the immediate children of this node; the visitor
// returns false to stop.
func (n *SemanticsNode) VisitChildren(visitor SemanticsNodeVisitor) {
	for _, child := range n.children {
		if !visitor(child) {
			return
		}
	}
}

func (n *SemanticsNode) visitDescendants(visitor SemanticsNodeVisitor) bool {
	for _, child := range n.children {
		if !visitor(child) || !child.visitDescendants(visitor) {
			return false
		}
	}
	return true
}

// Owner is the owner for this node (nil if unattached).
func (n *SemanticsNode) Owner() *SemanticsOwner { return n.owner }

// Attached is whether the semantics tree this node belongs to is attached
// to a SemanticsOwner.
func (n *SemanticsNode) Attached() bool { return n.owner != nil }

