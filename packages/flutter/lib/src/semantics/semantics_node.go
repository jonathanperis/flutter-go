func (n *SemanticsNode) TraversalParent() *SemanticsNode {
	if n.traversalParent != nil {
		return n.traversalParent
	}
	return n.parent
}

// SetTraversalParent sets TraversalParent.
func (n *SemanticsNode) SetTraversalParent(value *SemanticsNode) {
	if n.traversalParent == value {
		return
	}
	n.traversalParent = value
	n.markDirty()
}

// Depth is the depth of this node in the semantics tree (0 for the root).
func (n *SemanticsNode) Depth() int { return n.depth }

func (n *SemanticsNode) redepthChild(child *SemanticsNode) {
	dartAssert(child.Owner() == n.Owner(), nil)
	if child.depth <= n.depth {
		child.depth = n.depth + 1
		child.redepthChildren()
	}
}

func (n *SemanticsNode) redepthChildren() {
	for _, child := range n.children {
		n.redepthChild(child)
	}
}

func (n *SemanticsNode) updateChildMergeFlagRecursively(child *SemanticsNode) {
	dartAssert(child.Owner() == n.Owner(), nil)
	childShouldMergeToParent := n.IsPartOfNodeMerging()
	if childShouldMergeToParent == child.IsMergedIntoParent() {
		return
	}
	child.SetIsMergedIntoParent(childShouldMergeToParent)
	if child.MergeAllDescendantsIntoThisNode() {
		// No need to update the descendants since `child` has the merge flag
		// set.
	} else {
		child.updateChildrenMergeFlags()
	}
}

func (n *SemanticsNode) updateChildrenMergeFlags() {
	for _, child := range n.children {
		n.updateChildMergeFlagRecursively(child)
	}
}

func (n *SemanticsNode) adoptChild(child *SemanticsNode) {
	dartAssert(child.parent == nil, nil)
	if foundation.KDebugMode {
		node := n
		for node.Parent() != nil {
			node = node.Parent()
		}
		dartAssert(node != child, nil) // indicates we are about to create a cycle
	}
	child.parent = n
	if n.Attached() {
		child.Attach(n.owner)
	}
	n.redepthChild(child)
	// In most cases, child should have up to date `isMergedIntoParent` since
	// it was set during _RenderObjectSemantics.buildSemantics. However, it is
	// still possible that this child was an extra node introduced in
	// RenderObject.assembleSemanticsNode. We have to make sure their
	// `isMergedIntoParent` is updated correctly.
	n.updateChildMergeFlagRecursively(child)
}

func (n *SemanticsNode) dropChild(child *SemanticsNode) {
	dartAssert(child.parent == n, nil)
	dartAssert(child.Attached() == n.Attached(), nil)
	child.parent = nil
	if n.Attached() {
		child.Detach()
	}
}

// Attach marks this node as attached to the given owner (visible for
// testing).
func (n *SemanticsNode) Attach(owner *SemanticsOwner) {
	dartAssert(n.owner == nil, nil)
	n.owner = owner
	for {
		if _, used := owner.nodes[n.id]; !used {
			break
		}
		// Ids may repeat if the Flutter has generated > 2^16 ids. We need to
		// keep regenerating the id until we found an id that is not used.
		n.id = generateNewID()
	}
	owner.nodes[n.id] = n
	delete(owner.detachedNodes, n)
	if n.dirty {
		n.dirty = false
		n.markDirty()
	}
	for _, child := range n.children {
		child.Attach(owner)
	}
}

// Detach marks this node as detached from its owner (visible for testing).
func (n *SemanticsNode) Detach() {
	dartAssert(n.owner != nil, nil)
	_, has := n.owner.nodes[n.id]
	dartAssert(has, nil)
	_, detached := n.owner.detachedNodes[n]
	dartAssert(!detached, nil)
	owner := n.owner
	delete(owner.nodes, n.id)
	owner.detachedNodes[n] = struct{}{}
	if identifier := n.traversalChildIdentifier; identifier != nil {
		if p := owner.traversalParentNodes[identifier]; p != nil {
			p.markDirty()
		}
	}
	// Clean up the according entry in owner._traversalParentNodes map.
	for key, node := range owner.traversalParentNodes {
		if node == n {
			delete(owner.traversalParentNodes, key)
		}
	}
	// Clean up this node from the value set in owner._traversalChildNodes
	// map.
	for key, childSet := range owner.traversalChildNodes {
		childSet.remove(n)
		if childSet.isEmpty() {
			delete(owner.traversalChildNodes, key)
		}
	}
	n.owner = nil
	dartAssert(n.Parent() == nil || n.Attached() == n.Parent().Attached(), nil)
	for _, child := range n.children {
		// The list of children may be stale and may contain nodes that have
		// been assigned to a different parent.
		if child.Parent() == n {
			child.Detach()
		}
	}
	// The other side will have forgotten this node if we ever send it again,
	// so make sure to mark it dirty so that it'll get sent if it is
	// resurrected.
	n.markDirty()
}

// ---- DIRTY MANAGEMENT

func (n *SemanticsNode) markDirty() {
	if n.dirty {
		return
	}
	n.dirty = true
	if n.Attached() {
		_, detached := n.owner.detachedNodes[n]
		dartAssert(!detached, nil)
		n.owner.dirtyNodes.add(n)
	}
}

// DebugIsDirty is whether this node needs to be sent to the engine (nil
// outside debug builds; visible for testing).
func (n *SemanticsNode) DebugIsDirty() *bool {
	if foundation.KDebugMode {
		isDirty := n.dirty
		return &isDirty
	}
	return nil
}

func (n *SemanticsNode) isDifferentFromCurrentSemanticAnnotation(config *SemanticsConfiguration) bool {
	return !n.attributedLabel.Equal(config.AttributedLabel()) ||
		!n.attributedHint.Equal(config.AttributedHint()) ||
		!n.attributedValue.Equal(config.AttributedValue()) ||
		!n.attributedIncreasedValue.Equal(config.AttributedIncreasedValue()) ||
		!n.attributedDecreasedValue.Equal(config.AttributedDecreasedValue()) ||
		n.tooltip != config.Tooltip() ||
		n.flags != config.flags ||
		!ptrEqual(n.textDirection, config.TextDirection()) ||
		n.sortKey != config.sortKey ||
		!textSelectionsEqual(n.textSelection, config.textSelection) ||
		!ptrEqual(n.scrollPosition, config.scrollPosition) ||
		!ptrEqual(n.scrollExtentMax, config.scrollExtentMax) ||
		!ptrEqual(n.scrollExtentMin, config.scrollExtentMin) ||
		n.actionsAsBits != config.actionsAsBits ||
		!ptrEqual(n.IndexInParent, config.IndexInParent()) ||
		!ptrEqual(n.PlatformViewID(), config.PlatformViewID()) ||
		!ptrEqual(n.maxValueLength, config.maxValueLength) ||
		!ptrEqual(n.currentValueLength, config.currentValueLength) ||
		n.mergeAllDescendantsIntoThisNode != config.IsMergingSemanticsOfDescendants() ||
		n.areUserActionsBlocked != config.IsBlockingUserActions ||
		n.headingLevel != config.headingLevel ||
		!urlsEqual(n.linkURL, config.linkURL) ||
		n.role != config.Role() ||
		n.validationResult != config.ValidationResult() ||
		n.hitTestBehavior != config.HitTestBehavior() ||
		!objectsEqual(n.traversalChildIdentifier, config.traversalChildIdentifier) ||
		!objectsEqual(n.traversalParentIdentifier, config.traversalParentIdentifier) ||
		!ptrEqual(n.minValue, config.minValue) ||
		!ptrEqual(n.maxValue, config.maxValue) ||
		!customActionsEqual(n.customSemanticsActions, config.customSemanticsActions)
}

