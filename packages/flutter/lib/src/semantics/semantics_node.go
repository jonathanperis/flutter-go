// SemanticsNodeUpdateWithOptions are updateWith's named parameters (Config
// nil: the empty configuration; ChildrenInInversePaintOrder nil: none).
type SemanticsNodeUpdateWithOptions struct {
	Config                      *SemanticsConfiguration
	ChildrenInInversePaintOrder []*SemanticsNode
}

// UpdateWith reconfigures the properties of this object to describe the
// configuration provided, and replaces the children.
func (n *SemanticsNode) UpdateWith(opts SemanticsNodeUpdateWithOptions) {
	config := opts.Config
	if config == nil {
		config = kEmptyConfig()
	}
	if n.isDifferentFromCurrentSemanticAnnotation(config) {
		n.markDirty()
	}
	dartAssert(config.PlatformViewID() == nil || len(opts.ChildrenInInversePaintOrder) == 0,
		"SemanticsNodes with children must not specify a platformViewId.")

	mergeAllDescendantsIntoThisNodeValueChanged := n.mergeAllDescendantsIntoThisNode != config.IsMergingSemanticsOfDescendants()

	n.identifier = config.Identifier()
	n.traversalParentIdentifier = config.TraversalParentIdentifier()
	n.traversalChildIdentifier = config.TraversalChildIdentifier()
	n.attributedLabel = config.AttributedLabel()
	n.attributedValue = config.AttributedValue()
	n.attributedIncreasedValue = config.AttributedIncreasedValue()
	n.attributedDecreasedValue = config.AttributedDecreasedValue()
	n.attributedHint = config.AttributedHint()
	n.tooltip = config.Tooltip()
	n.hintOverrides = config.HintOverrides()
	n.flags = config.flags
	n.textDirection = config.TextDirection()
	n.sortKey = config.SortKey()
	n.actions = make(map[ui.SemanticsAction]SemanticsActionHandler, len(config.actions))
	for k, v := range config.actions {
		n.actions[k] = v
	}
	n.customSemanticsActions = append(customActionEntries{}, config.customSemanticsActions...)
	n.actionsAsBits = config.actionsAsBits
	n.textSelection = config.textSelection
	isMultiline := config.IsMultiline()
	n.isMultiline = &isMultiline
	n.scrollPosition = config.scrollPosition
	n.scrollExtentMax = config.scrollExtentMax
	n.scrollExtentMin = config.scrollExtentMin
	n.mergeAllDescendantsIntoThisNode = config.IsMergingSemanticsOfDescendants()
	n.scrollChildCount = config.ScrollChildCount()
	n.scrollIndex = config.ScrollIndex()
	n.IndexInParent = config.IndexInParent()
	n.platformViewID = config.platformViewID
	n.maxValueLength = config.maxValueLength
	n.currentValueLength = config.currentValueLength
	n.areUserActionsBlocked = config.IsBlockingUserActions
	n.headingLevel = config.headingLevel
	n.linkURL = config.linkURL
	n.role = config.role
	n.controlsNodes = config.controlsNodes
	n.validationResult = config.validationResult
	n.hitTestBehavior = config.hitTestBehavior
	n.inputType = config.inputType
	n.locale = config.Locale
	n.minValue = config.MinValue()
	n.maxValue = config.MaxValue()

	children := opts.ChildrenInInversePaintOrder
	if children == nil {
		children = []*SemanticsNode{}
	}
	n.replaceChildren(children)

	if mergeAllDescendantsIntoThisNodeValueChanged {
		n.updateChildrenMergeFlags()
	}

	dartAssert(!n.canPerformAction(ui.SemanticsActionIncrease) || (n.Value() == "") == (n.IncreasedValue() == ""),
		`A SemanticsNode with action "increase" needs to be annotated with either both "value" and "increasedValue" or neither`)
	dartAssert(!n.canPerformAction(ui.SemanticsActionDecrease) || (n.Value() == "") == (n.DecreasedValue() == ""),
		`A SemanticsNode with action "decrease" needs to be annotated with either both "value" and "decreasedValue" or neither`)
}

// orFirst is Dart's ??= on a nullable value.
func orFirst[T any](a, b *T) *T {
	if a != nil {
		return a
	}
	return b
}

// GetSemanticsData returns a summary of the semantics for this node; if
// this node has MergeAllDescendantsIntoThisNode, it includes the
// descendants'.
func (n *SemanticsNode) GetSemanticsData() *SemanticsData {
	flags := n.flags
	// Can't use _effectiveActionsAsBits here. The filtering of action bits
	// must be done after the merging the its descendants.
	actions := n.actionsAsBits
	identifier := n.identifier
	traversalParentIdentifier := n.traversalParentIdentifier
	traversalChildIdentifier := n.traversalChildIdentifier
	attributedLabel := n.attributedLabel
	attributedValue := n.attributedValue
	attributedIncreasedValue := n.attributedIncreasedValue
	attributedDecreasedValue := n.attributedDecreasedValue
	attributedHint := n.attributedHint
	tooltip := n.tooltip
	textDirection := n.textDirection
	var mergedTags []*SemanticsTag
	if n.Tags != nil {
		mergedTags = addTags([]*SemanticsTag{}, n.Tags)
	}
	textSelection := n.textSelection
	scrollChildCount := n.scrollChildCount
	scrollIndex := n.scrollIndex
	scrollPosition := n.scrollPosition
	scrollExtentMax := n.scrollExtentMax
	scrollExtentMin := n.scrollExtentMin
	platformViewID := n.platformViewID
	maxValueLength := n.maxValueLength
	currentValueLength := n.currentValueLength
	headingLevel := n.headingLevel
	linkURL := n.linkURL
	role := n.role
	controlsNodes := n.controlsNodes
	validationResult := n.validationResult
	hitTestBehavior := n.hitTestBehavior
	inputType := n.inputType
	locale := n.locale
	customSemanticsActionIDs := newOrderedSet[int]()
	minValue := n.minValue
	maxValue := n.maxValue
	for _, e := range n.customSemanticsActions {
		customSemanticsActionIDs.add(CustomSemanticsActionGetIdentifier(e.Key))
	}
	addHintOverrides := func(hintOverrides *SemanticsHintOverrides) {
		if hintOverrides == nil {
			return
		}
		if hintOverrides.OnTapHint != nil {
			action := NewCustomSemanticsActionOverridingAction(*hintOverrides.OnTapHint, ui.SemanticsActionTap)
			customSemanticsActionIDs.add(CustomSemanticsActionGetIdentifier(action))
		}
		if hintOverrides.OnLongPressHint != nil {
			action := NewCustomSemanticsActionOverridingAction(*hintOverrides.OnLongPressHint, ui.SemanticsActionLongPress)
			customSemanticsActionIDs.add(CustomSemanticsActionGetIdentifier(action))
		}
	}
	addHintOverrides(n.HintOverrides())

	if n.MergeAllDescendantsIntoThisNode() {
		n.visitDescendants(func(node *SemanticsNode) bool {
			dartAssert(node.IsMergedIntoParent(), nil)
			flags = flags.Merge(node.flags)
			actions |= node.effectiveActionsAsBits()
			textDirection = orFirst(textDirection, node.textDirection)
			textSelection = orFirst(textSelection, node.textSelection)
			scrollChildCount = orFirst(scrollChildCount, node.scrollChildCount)
			scrollIndex = orFirst(scrollIndex, node.scrollIndex)
			scrollPosition = orFirst(scrollPosition, node.scrollPosition)
			scrollExtentMax = orFirst(scrollExtentMax, node.scrollExtentMax)
			scrollExtentMin = orFirst(scrollExtentMin, node.scrollExtentMin)
			platformViewID = orFirst(platformViewID, node.platformViewID)
			maxValueLength = orFirst(maxValueLength, node.maxValueLength)
			currentValueLength = orFirst(currentValueLength, node.currentValueLength)
			linkURL = orFirst(linkURL, node.linkURL)
			headingLevel = mergeHeadingLevels(node.headingLevel, headingLevel)

			if identifier == "" {
				identifier = node.identifier
			}
			if traversalParentIdentifier == nil {
				traversalParentIdentifier = node.TraversalParentIdentifier()
			}
			if traversalChildIdentifier == nil {
				traversalChildIdentifier = node.TraversalChildIdentifier()
			}
			if attributedValue.Text == "" {
				attributedValue = node.attributedValue
			}
			if attributedIncreasedValue.Text == "" {
				attributedIncreasedValue = node.attributedIncreasedValue
			}
			if attributedDecreasedValue.Text == "" {
				attributedDecreasedValue = node.attributedDecreasedValue
			}
			if role == ui.SemanticsRoleNone {
				role = node.role
			}
			if inputType == ui.SemanticsInputTypeNone {
				inputType = node.inputType
			}
			if hitTestBehavior == ui.SemanticsHitTestBehaviorDefer {
				hitTestBehavior = node.hitTestBehavior
			}
			if tooltip == "" {
				tooltip = node.tooltip
			}
			if node.Tags != nil {
				if mergedTags == nil {
					mergedTags = []*SemanticsTag{}
				}
				mergedTags = addTags(mergedTags, node.Tags)
			}
			for _, e := range node.customSemanticsActions {
				customSemanticsActionIDs.add(CustomSemanticsActionGetIdentifier(e.Key))
			}
			addHintOverrides(node.HintOverrides())
			attributedLabel = concatAttributedString(attributedLabel, textDirection, node.attributedLabel, node.textDirection)
			attributedHint = concatAttributedString(attributedHint, textDirection, node.attributedHint, node.textDirection)

			if controlsNodes == nil {
				controlsNodes = node.controlsNodes
			} else if node.controlsNodes != nil {
				controlsNodes = unionStrings(controlsNodes, node.controlsNodes)
			}

			minValue = orFirst(minValue, node.minValue)
			maxValue = orFirst(maxValue, node.maxValue)

			if validationResult == ui.SemanticsValidationResultNone {
				validationResult = node.validationResult
			} else if validationResult == ui.SemanticsValidationResultValid {
				// When merging nodes, invalid validation result takes precedence.
				// Otherwise, validation information could be lost.
				if node.validationResult != ui.SemanticsValidationResultNone &&
					node.validationResult != ui.SemanticsValidationResultValid {
					validationResult = node.validationResult
				}
			}
			return true
		})
	}

	resultActions := actions
	if n.areUserActionsBlocked {
		resultActions = actions & kUnblockedUserActions
	}
	ids := customSemanticsActionIDs.toList()
	dart.ListSort(ids, dart.CompareInts)
	return NewSemanticsData(SemanticsDataOptions{
		FlagsCollection:           flags,
		Actions:                   resultActions,
		Identifier:                identifier,
		TraversalParentIdentifier: traversalParentIdentifier,
		TraversalChildIdentifier:  traversalChildIdentifier,
		AttributedLabel:           attributedLabel,
		AttributedValue:           attributedValue,
		AttributedIncreasedValue:  attributedIncreasedValue,
		AttributedDecreasedValue:  attributedDecreasedValue,
		AttributedHint:            attributedHint,
		Tooltip:                   tooltip,
		TextDirection:             textDirection,
		Rect:                      n.Rect(),
		Transform:                 n.Transform(),
		Tags:                      mergedTags,
		TextSelection:             textSelection,
		ScrollChildCount:          scrollChildCount,
		ScrollIndex:               scrollIndex,
		ScrollPosition:            scrollPosition,
		ScrollExtentMax:           scrollExtentMax,
		ScrollExtentMin:           scrollExtentMin,
		PlatformViewID:            platformViewID,
		MaxValueLength:            maxValueLength,
		CurrentValueLength:        currentValueLength,
		CustomSemanticsActionIDs:  ids,
		HeadingLevel:              headingLevel,
		LinkURL:                   linkURL,
		Role:                      role,
		ControlsNodes:             controlsNodes,
		ValidationResult:          validationResult,
		HitTestBehavior:           hitTestBehavior,
		InputType:                 inputType,
		Locale:                    locale,
		MinValue:                  minValue,
		MaxValue:                  maxValue,
	})
}

// addTags is set.addAll on an ordered tag set.
func addTags(set, tags []*SemanticsTag) []*SemanticsTag {
	for _, t := range tags {
		if !containsTag(set, t) {
			set = append(set, t)
		}
	}
	return set
}

func computeTraversalTransform(parent, child *SemanticsNode) *vm.Matrix4 {
	traversalTransform := vm.NewMatrix4Identity()
	var parentToCommonAncestorTransform *vm.Matrix4
	fromNode := child
	toNode := parent
	// Find the common ancestor.
	for fromNode != toNode {
		fromDepth := fromNode.Depth()
		toDepth := toNode.Depth()
		if fromDepth >= toDepth {
			if transform := fromNode.Transform(); transform != nil {
				traversalTransform.Multiply(transform)
			}
			fromNode = fromNode.Parent()
		}
		if fromDepth <= toDepth {
			if parentToCommonAncestorTransform == nil {
				parentToCommonAncestorTransform = vm.NewMatrix4Identity()
			}
			if transform := toNode.Transform(); transform != nil {
				parentToCommonAncestorTransform.Multiply(transform)
			}
			toNode = toNode.Parent()
		}
	}
	if parentToCommonAncestorTransform != nil {
		if parentToCommonAncestorTransform.Invert() != 0 {
			traversalTransform.Multiply(parentToCommonAncestorTransform)
		} else {
			traversalTransform.SetZero()
		}
	}
	return traversalTransform
}

func (n *SemanticsNode) childrenIDInTraversalOrder() []int32 {
	sortedChildren := n.childrenInTraversalOrder()
	childrenInTraversalOrder := make([]int32, len(sortedChildren))
	for i := range sortedChildren {
		childrenInTraversalOrder[i] = int32(sortedChildren[i].ID())
	}
	return childrenInTraversalOrder
}

func (n *SemanticsNode) childrenInHitTestOrder() []*SemanticsNode {
	if n.children == nil {
		return []*SemanticsNode{}
	}
	if foundation.KIsWeb || n.isTraversalParent() {
		return n.children
	}
	// If a child node is not in the traversal tree after grafting, it is
	// dropped from the hit-test tree to keep the two trees in sync.
	// Otherwise, the user might accidentally hit test a node that cannot be
	// traversed.
	result := []*SemanticsNode{}
	for _, child := range n.children {
		if child.isTraversalChild() {
			traversalParent := n.Owner().traversalParentNodes[child.GetSemanticsData().TraversalChildIdentifier]
			if traversalParent == nil {
				continue
			}
		}
		result = append(result, child)
	}
	return result
}

func (n *SemanticsNode) childrenIDInHitTestOrder() []int32 {
	children := n.childrenInHitTestOrder()
	ids := make([]int32, 0, len(children))
	for i := len(children) - 1; i >= 0; i-- {
		ids = append(ids, int32(children[i].ID()))
	}
	return ids
}

var (
	kEmptyChildList                          = []int32{}
	kEmptyCustomSemanticsActionsList         = []int32{}
	kIdentityTransform                       = vm.NewMatrix4Identity()
	semanticsNaN                             = math.NaN()
	dartPi                           float64 = math.Pi
)

func (n *SemanticsNode) addToUpdate(builder ui.SemanticsUpdateBuilder, customSemanticsActionIDsUpdate *orderedSet[int]) {
	dartAssert(n.dirty, nil)
	data := n.GetSemanticsData()
	if foundation.KDebugMode {
		if err := checkSemanticsData(n); err != nil {
			panic(err)
		}
	}
	var childrenInTraversalOrder, childrenInHitTestOrder []int32
	if !n.HasChildren() || n.MergeAllDescendantsIntoThisNode() {
		if n.isTraversalParent() && !foundation.KIsWeb {
			// If the current node is a traversal parent node but it has no
			// children in hit-test order, it means childrenIntraversalOrder will
			// only contain its traversalChildren in _traversalChildNodes map.
			if traversalChildren, ok := n.traversalChildSet(); ok {
				index := 0
				childrenInTraversalOrder = make([]int32, traversalChildren.length())
				for _, node := range traversalChildren.toList() {
					if node.Attached() {
						childrenInTraversalOrder[index] = int32(node.ID())
						index++
					}
				}
			} else {
				childrenInTraversalOrder = kEmptyChildList
			}
			childrenInHitTestOrder = kEmptyChildList
		} else {
			childrenInTraversalOrder = kEmptyChildList
			childrenInHitTestOrder = kEmptyChildList
		}
	} else {
		childrenInTraversalOrder = n.childrenIDInTraversalOrder()
		childrenInHitTestOrder = n.childrenIDInHitTestOrder()
	}
	var customSemanticsActionIDs []int32
	if len(data.CustomSemanticsActionIDs) > 0 {
		customSemanticsActionIDs = make([]int32, len(data.CustomSemanticsActionIDs))
		for i, id := range data.CustomSemanticsActionIDs {
			customSemanticsActionIDs[i] = int32(id)
			customSemanticsActionIDsUpdate.add(id)
		}
	}
	traversalParentID := -1
	if identifier := data.TraversalChildIdentifier; identifier != nil {
		if parentNode := n.Owner().traversalParentNodes[identifier]; parentNode != nil {
			traversalParentID = parentNode.ID()
		}
	}

	if childIdentifier := n.TraversalChildIdentifier(); childIdentifier != nil {
		n.SetTraversalParent(n.Owner().traversalParentNodes[childIdentifier])
		if !foundation.KIsWeb {
			traversalParent := n.TraversalParent()
			dartAssert(traversalParent != nil, "Null check operator used on a null value")
			n.traversalChildTransform = computeTraversalTransform(traversalParent, n)
		}
	}

	textSelectionBase, textSelectionExtent := -1, -1
	if data.TextSelection != nil {
		textSelectionBase = data.TextSelection.BaseOffset
		textSelectionExtent = data.TextSelection.ExtentOffset
	}
	traversalTransform := n.traversalTransform()
	if traversalTransform == nil {
		traversalTransform = kIdentityTransform
	}
	hitTestTransform := data.Transform
	if hitTestTransform == nil {
		hitTestTransform = kIdentityTransform
	}
	if customSemanticsActionIDs == nil {
		customSemanticsActionIDs = kEmptyCustomSemanticsActionsList
	}
	linkURL := ""
	if data.LinkURL != nil {
		linkURL = data.LinkURL.String()
	}
	var controlsNodes []string
	if data.ControlsNodes != nil {
		controlsNodes = append([]string{}, data.ControlsNodes...)
	}
	builder.UpdateNode(ui.SemanticsUpdateBuilderUpdateNodeOptions{
		ID:                       n.ID(),
		Flags:                    data.FlagsCollection,
		Actions:                  data.Actions,
		Rect:                     data.Rect,
		Identifier:               data.Identifier,
		Label:                    data.AttributedLabel.Text,
		LabelAttributes:          data.AttributedLabel.Attributes,
		Value:                    data.AttributedValue.Text,
		ValueAttributes:          data.AttributedValue.Attributes,
		IncreasedValue:           data.AttributedIncreasedValue.Text,
		IncreasedValueAttributes: data.AttributedIncreasedValue.Attributes,
		DecreasedValue:           data.AttributedDecreasedValue.Text,
		DecreasedValueAttributes: data.AttributedDecreasedValue.Attributes,
		Hint:                     data.AttributedHint.Text,
		HintAttributes:           data.AttributedHint.Attributes,
		Tooltip:                  data.Tooltip,
		TextDirection:            data.TextDirection,
		TextSelectionBase:        textSelectionBase,
		TextSelectionExtent:      textSelectionExtent,
		PlatformViewID:           intOr(data.PlatformViewID, -1),
		MaxValueLength:           intOr(data.MaxValueLength, -1),
		CurrentValueLength:       intOr(data.CurrentValueLength, -1),
		ScrollChildren:           intOr(data.ScrollChildCount, 0),
		ScrollIndex:              intOr(data.ScrollIndex, 0),
		ScrollPosition:           floatOr(data.ScrollPosition, semanticsNaN),
		ScrollExtentMax:          floatOr(data.ScrollExtentMax, semanticsNaN),
		ScrollExtentMin:          floatOr(data.ScrollExtentMin, semanticsNaN),
		Transform:                traversalTransform.Storage(),
		TraversalParent:          traversalParentID,
		HitTestTransform:         hitTestTransform.Storage(),
		ChildrenInTraversalOrder: childrenInTraversalOrder,
		ChildrenInHitTestOrder:   childrenInHitTestOrder,
		AdditionalActions:        customSemanticsActionIDs,
		HeadingLevel:             data.HeadingLevel,
		LinkURL:                  linkURL,
		Role:                     data.Role,
		ControlsNodes:            controlsNodes,
		ValidationResult:         data.ValidationResult,
		HitTestBehavior:          data.HitTestBehavior,
		InputType:                data.InputType,
		Locale:                   data.Locale,
		MinValue:                 strOr(data.MinValue, ""),
		MaxValue:                 strOr(data.MaxValue, ""),
	})
	n.dirty = false
}

func intOr(p *int, d int) int {
	if p != nil {
		return *p
	}
	return d
}

func floatOr(p *float64, d float64) float64 {
	if p != nil {
		return *p
	}
	return d
}

func strOr(p *string, d string) string {
	if p != nil {
		return *p
	}
	return d
}

// traversalChildSet is owner._traversalChildNodes[traversalParentIdentifier]
// (ok false when the owner is nil or has no entry).
func (n *SemanticsNode) traversalChildSet() (*orderedSet[*SemanticsNode], bool) {
	if n.Owner() == nil {
		return nil, false
	}
	s, ok := n.Owner().traversalChildNodes[n.TraversalParentIdentifier()]
	return s, ok
}

// updateChildrenInTraversalOrder generates a children list in traversal
// order, grafting traversal children onto their traversal parents.
func (n *SemanticsNode) updateChildrenInTraversalOrder() []*SemanticsNode {
	if foundation.KIsWeb {
		return n.children
	}
	updatedChildren := []*SemanticsNode{}
	for _, child := range n.children {
		if child.isTraversalChild() && !n.isTraversalParent() {
			// If the child node is a traversal child, but the current node is
			// not a traversal parent, the child node is grafted onto the
			// traversal parent with the same identifier, so it is not added
			// here. A traversal parent that is, in paint order, a child of the
			// traversal child would make an infinite loop.
			traversalParent := n.Owner().traversalParentNodes[child.GetSemanticsData().TraversalChildIdentifier]
			traversalParentID := "null"
			if traversalParent != nil {
				traversalParentID = strconv.Itoa(traversalParent.ID())
			}
			for traversalParent != nil {
				if traversalParent == child {
					panic(foundation.NewFlutterError("The traversalParent " + traversalParentID +
						" cannot be the child of the traversalChild " + strconv.Itoa(child.ID()) + " in hit-test order"))
				}
				traversalParent = traversalParent.Parent()
			}
			continue
		}
		updatedChildren = append(updatedChildren, child)
	}

	// If the current node is a traversal parent node, part of its traversal
	// children might be on other branches of the hit-test tree and need to
	// be grafted.
	if n.isTraversalParent() {
		var traversalChildren *orderedSet[*SemanticsNode]
		if n.Owner() != nil {
			traversalChildren = n.Owner().traversalChildNodes[n.TraversalParentIdentifier()]
		}
		if traversalChildren != nil {
			// When traversal children are grafted from other branches, make sure
			// these children are not ancestors of the traversal parent.
			// Otherwise, it will cause infinite loop.
			currentNode := n
			for currentNode.Parent() != nil {
				currentNode = currentNode.Parent()
				if traversalChildren.contains(currentNode) {
					panic(foundation.NewFlutterError("The traversalParent " + strconv.Itoa(n.ID()) +
						" cannot be the child of the traversalChild " + strconv.Itoa(currentNode.ID()) + " in hit-test order"))
				}
			}
			for _, node := range traversalChildren.toList() {
				if node.Attached() {
					updatedChildren = append(updatedChildren, node)
				}
			}
		}
	}
	return updatedChildren
}

func (n *SemanticsNode) childrenInTraversalOrder() []*SemanticsNode {
	updatedChildren := n.updateChildrenInTraversalOrder()
	inheritedTextDirection := n.TextDirection()
	ancestor := n.Parent()
	for inheritedTextDirection == nil && ancestor != nil {
		inheritedTextDirection = ancestor.TextDirection()
		ancestor = ancestor.Parent()
	}

	var childrenInDefaultOrder []*SemanticsNode
	if inheritedTextDirection != nil {
		childrenInDefaultOrder = childrenInDefaultOrderOf(updatedChildren, *inheritedTextDirection)
	} else {
		// In the absence of text direction default to paint order.
		childrenInDefaultOrder = updatedChildren
	}

	// List.sort does not guarantee stable sort order. Therefore, children are
	// first partitioned into groups that have compatible sort keys, i.e. keys
	// in the same group can be compared to each other. These groups stay in
	// the same place. Only children within the same group are sorted.
	everythingSorted := []*traversalSortNode{}
	sortNodes := []*traversalSortNode{}
	var lastSortKey SemanticsSortKey
	for position := 0; position < len(childrenInDefaultOrder); position++ {
		child := childrenInDefaultOrder[position]
		sortKey := child.SortKey()
		lastSortKey = nil
		if position > 0 {
			lastSortKey = childrenInDefaultOrder[position-1].SortKey()
		}
		isCompatibleWithPreviousSortKey := position == 0 ||
			runtimeType(sortKey) == runtimeType(lastSortKey) &&
				(sortKey == nil || ptrEqual(sortKey.Name(), lastSortKey.Name()))
		if !isCompatibleWithPreviousSortKey && len(sortNodes) > 0 {
			// Do not sort groups with null sort keys. List.sort does not
			// guarantee a stable sort order.
			if lastSortKey != nil {
				dart.ListSort(sortNodes, compareTraversalSortNodes)
			}
			everythingSorted = append(everythingSorted, sortNodes...)
			sortNodes = sortNodes[:0:0]
		}
		sortNodes = append(sortNodes, &traversalSortNode{node: child, sortKey: sortKey, position: position})
	}

	// Do not sort groups with null sort keys. List.sort does not guarantee a
	// stable sort order.
	if lastSortKey != nil {
		dart.ListSort(sortNodes, compareTraversalSortNodes)
	}
	everythingSorted = append(everythingSorted, sortNodes...)

	result := make([]*SemanticsNode, len(everythingSorted))
	for i, sortNode := range everythingSorted {
		result[i] = sortNode.node
	}
	return result
}

// SendEvent sends a SemanticsEvent associated with this node through
// SystemChannels.accessibility (only when attached); errors are reported
// to FlutterError.onError.
func (n *SemanticsNode) SendEvent(event SemanticsEvent) {
	if !n.Attached() {
		return
	}
	id := n.ID()
	future := services.SystemChannels.Accessibility.Send(event.ToMap(SemanticsEventToMapOptions{NodeID: &id}))
	async.OnComplete(future, func(any) {}, func(err error) {
		library := "semantics library"
		foundation.FlutterErrorReportError(foundation.NewFlutterErrorDetails(err, foundation.FlutterErrorDetailsOptions{
			Library: &library,
			Context: foundation.NewErrorDescription("while sending accessibility event"),
			InformationCollector: func() iter.Seq[foundation.DiagnosticsNode] {
				return slices.Values([]foundation.DiagnosticsNode{
					foundation.NewDiagnosticsProperty[SemanticsEvent]("event", event),
					foundation.NewDiagnosticsProperty("node", n),
				})
			},
		}))
	})
}

func (n *SemanticsNode) debugIsActionBlocked(action ui.SemanticsAction) bool {
	result := false
	if foundation.KDebugMode {
		result = n.effectiveActionsAsBits()&action.Index() == 0
	}
	return result
}

