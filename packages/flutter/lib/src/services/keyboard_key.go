// LogicalKeyboardKeyIsControlCharacter is
// LogicalKeyboardKey.isControlCharacter: whether label is one Unicode
// control character.
func LogicalKeyboardKeyIsControlCharacter(label string) bool {
	if dart.StringLength(label) != 1 {
		return false
	}
	codeUnit := dart.CodeUnitAt(label, 0)
	return (codeUnit <= 0x1f && codeUnit >= 0x00) || (codeUnit >= 0x7f && codeUnit <= 0x9f)
}

// IsAutogenerated is whether the key id was generated by Flutter for a
// platform key code it doesn't recognize.
func (k LogicalKeyboardKey) IsAutogenerated() bool {
	return k.KeyID&LogicalKeyboardKeyPlaneMask >= LogicalKeyboardKeyStartOfPlatformPlanes
}

type keySynonyms struct {
	key      LogicalKeyboardKey
	synonyms []LogicalKeyboardKey
}

func lookUpSynonyms(table []keySynonyms, key LogicalKeyboardKey) []LogicalKeyboardKey {
	for _, e := range table {
		if e.key == key {
			return e.synonyms
		}
	}
	return nil
}

// Synonyms is the set of pseudo-key synonyms of this key (shiftLeft's is
// {shift}); a Dart Set, as a slice in its iteration order.
func (k LogicalKeyboardKey) Synonyms() []LogicalKeyboardKey {
	return slices.Clone(lookUpSynonyms(logicalKeySynonyms, k))
}

// LogicalKeyboardKeyCollapseSynonyms is LogicalKeyboardKey.collapseSynonyms:
// input with the keys that have synonyms replaced by them (Dart sets are
// slices without duplicates, in iteration order).
func LogicalKeyboardKeyCollapseSynonyms(input []LogicalKeyboardKey) []LogicalKeyboardKey {
	return expandKeySet(input, logicalKeySynonyms)
}

// LogicalKeyboardKeyExpandSynonyms is LogicalKeyboardKey.expandSynonyms:
// input with the pseudo-keys expanded into their synonyms.
func LogicalKeyboardKeyExpandSynonyms(input []LogicalKeyboardKey) []LogicalKeyboardKey {
	return expandKeySet(input, logicalKeyReverseSynonyms)
}

func expandKeySet(input []LogicalKeyboardKey, table []keySynonyms) []LogicalKeyboardKey {
	out := []LogicalKeyboardKey{}
	for _, element := range input {
		replacement := lookUpSynonyms(table, element)
		if replacement == nil {
			replacement = []LogicalKeyboardKey{element}
		}
		for _, r := range replacement {
			if !slices.Contains(out, r) {
				out = append(out, r)
			}
		}
	}
	return out
}

