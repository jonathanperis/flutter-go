// KeyboardKey is the base of all keyboard key types (an abstract class
// with Diagnosticable).
type KeyboardKey interface {
	foundation.Diagnosticable
	isKeyboardKey()
}

// LogicalKeyboardKey describes a logical key: a key interpreted in the
// context of any modifiers, modes or keyboard layouts in effect. It is a
// comparable value (Dart's == compares the key ids); the constants are
// LogicalKeyboardKeyKeyA etc.
type LogicalKeyboardKey struct {
	// KeyID is a unique code representing this key.
	KeyID int
}

// NewLogicalKeyboardKey is LogicalKeyboardKey(keyId).
func NewLogicalKeyboardKey(keyID int) LogicalKeyboardKey { return LogicalKeyboardKey{KeyID: keyID} }

func (LogicalKeyboardKey) isKeyboardKey() {}

// Planes and masks of logical key ids (LogicalKeyboardKey's static
// constants).
const (
	// LogicalKeyboardKeyValueMask is the mask for the 32-bit value portion
	// of the key code.
	LogicalKeyboardKeyValueMask = 0x000ffffffff
	// LogicalKeyboardKeyPlaneMask is the mask for the plane prefix portion
	// of the key code.
	LogicalKeyboardKeyPlaneMask = 0x0ff00000000
	// LogicalKeyboardKeyUnicodePlane is the plane of keys which have a
	// Unicode representation.
	LogicalKeyboardKeyUnicodePlane = 0x00000000000
	// LogicalKeyboardKeyUnprintablePlane is the plane of keys defined by
	// Chromium without a Unicode representation.
	LogicalKeyboardKeyUnprintablePlane = 0x00100000000
	// LogicalKeyboardKeyFlutterPlane is the plane of keys defined by
	// Flutter.
	LogicalKeyboardKeyFlutterPlane = 0x00200000000
	// LogicalKeyboardKeyStartOfPlatformPlanes is the platform plane with the
	// lowest mask value, beyond which keys are considered autogenerated.
	LogicalKeyboardKeyStartOfPlatformPlanes = 0x01100000000
	// LogicalKeyboardKeyAndroidPlane: the Android embedding's private keys.
	LogicalKeyboardKeyAndroidPlane = 0x01100000000
	// LogicalKeyboardKeyFuchsiaPlane: the Fuchsia embedding's private keys.
	LogicalKeyboardKeyFuchsiaPlane = 0x01200000000
	// LogicalKeyboardKeyIosPlane: the iOS embedding's private keys.
	LogicalKeyboardKeyIosPlane = 0x01300000000
	// LogicalKeyboardKeyMacosPlane: the macOS embedding's private keys.
	LogicalKeyboardKeyMacosPlane = 0x01400000000
	// LogicalKeyboardKeyGtkPlane: the GTK embedding's private keys.
	LogicalKeyboardKeyGtkPlane = 0x01500000000
	// LogicalKeyboardKeyWindowsPlane: the Windows embedding's private keys.
	LogicalKeyboardKeyWindowsPlane = 0x01600000000
	// LogicalKeyboardKeyWebPlane: the Web embedding's private keys.
	LogicalKeyboardKeyWebPlane = 0x01700000000
	// LogicalKeyboardKeyGlfwPlane: the GLFW embedding's private keys.
	LogicalKeyboardKeyGlfwPlane = 0x01800000000
)

// nonValueBits returns the bits not in the value mask, shifted right.
func logicalNonValueBits(n int) int {
	const valueMaskWidth = 32
	const maxSafeIntegerWidth = 52
	const nonValueMask = (1 << (maxSafeIntegerWidth - valueMaskWidth)) - 1
	return (n >> valueMaskWidth) & nonValueMask
}

func logicalUnicodeKeyLabel(keyID int) *string {
	if logicalNonValueBits(keyID) == 0 {
		s := dart.StringToUpperCase(dart.StringFromCharCode(keyID))
		return &s
	}
	return nil
}

// KeyLabel is a description of the character the key produces (for
// printable keys, the character in upper case; otherwise the key's name,
// or "" when unknown).
func (k LogicalKeyboardKey) KeyLabel() string {
	if l := logicalUnicodeKeyLabel(k.KeyID); l != nil {
		return *l
	}
	return logicalKeyLabels[k.KeyID]
}

// DebugName is the debug string for this key (nil in release builds).
func (k LogicalKeyboardKey) DebugName() *string {
	if !foundation.KDebugMode {
		return nil
	}
	result, ok := logicalKeyLabels[k.KeyID]
	if !ok {
		if l := logicalUnicodeKeyLabel(k.KeyID); l != nil {
			result = "Key " + *l
		} else {
			result = "Key with ID 0x" + padLeft(strconv.FormatInt(int64(k.KeyID), 16), 11)
		}
	}
	return &result
}

func padLeft(s string, width int) string {
	if len(s) >= width {
		return s
	}
	return strings.Repeat("0", width-len(s)) + s
}

