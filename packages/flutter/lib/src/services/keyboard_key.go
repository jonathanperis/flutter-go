// diagnosticableToString is Diagnosticable.toString for value types that
// can't embed foundation.DiagnosticableMixin (it keeps a self pointer).
func diagnosticableToString(self foundation.Diagnosticable, opts []foundation.DiagnosticableToStringOptions) string {
	var o foundation.DiagnosticableToStringOptions
	if len(opts) > 0 {
		o = opts[0]
	}
	if foundation.KDebugMode {
		style := foundation.DiagnosticsTreeStyleSingleLine
		return self.ToDiagnosticsNode(foundation.ToDiagnosticsNodeOptions{Style: &style}).
			ToString(foundation.DiagnosticsNodeToStringOptions{MinLevel: o.MinLevel})
	}
	return self.ToStringShort()
}

func toDiagnosticableNode(self foundation.Diagnosticable, opts []foundation.ToDiagnosticsNodeOptions) foundation.DiagnosticsNode {
	var o foundation.DiagnosticableNodeOptions
	if len(opts) > 0 {
		o = foundation.DiagnosticableNodeOptions(opts[0])
	}
	return foundation.NewDiagnosticableNode[foundation.Diagnosticable](self, o)
}
