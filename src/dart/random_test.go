func TestRandomMatchesDart(t *testing.T) {
	for _, c := range randomExpected {
		r := NewRandom(c.seed)
		for i, want := range c.doubles {
			if got := r.NextDouble(); got != want {
				t.Errorf("seed %d nextDouble #%d = %v, Dart %v", c.seed, i, got, want)
			}
		}
		for i, m := range randomMaxes {
			if got := r.NextInt(m); got != c.ints[i] {
				t.Errorf("seed %d nextInt(%d) = %d, Dart %d", c.seed, m, got, c.ints[i])
			}
		}
		bools := ""
		for range 8 {
			if r.NextBool() {
				bools += "1"
			} else {
				bools += "0"
			}
		}
		if bools != c.bools {
			t.Errorf("seed %d nextBool = %s, Dart %s", c.seed, bools, c.bools)
		}
	}
}

func TestRandomSetupSeedZero(t *testing.T) {
	// Without the 0x5a17 substitution the state would stay 0 forever.
	if got := randomSetupSeed(9223367638806167551); got != 0x5a17 {
		t.Errorf("randomSetupSeed = %#x, want 0x5a17", got)
	}
}

var zero = 0.0

func TestRandomErrorsMatchDart(t *testing.T) {
	// Dart: try { Random(1).nextInt(m); } catch (e) { print(e); }
	for _, c := range []struct {
		max  int
		want string
	}{
		{0, "RangeError (max): Must be positive and <= 2^32: Not in inclusive range 1..4294967296: 0"},
		{-5, "RangeError (max): Must be positive and <= 2^32: Not in inclusive range 1..4294967296: -5"},
		{1<<32 + 1, "RangeError (max): Must be positive and <= 2^32: Not in inclusive range 1..4294967296: 4294967297"},
	} {
		func() {
			defer func() {
				if got := fmt.Sprint(recover()); got != c.want {
					t.Errorf("nextInt(%d) panicked with %q, Dart %q", c.max, got, c.want)
				}
			}()
			NewRandom(1).NextInt(c.max)
		}()
	}
	// Dart: print(ArgumentError.value(double.nan, 't', 'must not be NaN')).
	if got := NewArgumentErrorValue(zero/zero, "t", "must not be NaN").Error(); got != "Invalid argument (t): must not be NaN: NaN" {
		t.Errorf("ArgumentError = %q", got)
	}
	if got := (&UnimplementedError{}).Error(); got != "UnimplementedError" {
		t.Errorf("UnimplementedError = %q", got)
	}
}
