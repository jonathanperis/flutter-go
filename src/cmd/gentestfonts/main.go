// Command gentestfonts extracts the test fonts flutter_tester registers with
// --use-test-fonts (FlutterTest, Ahem, Cough) from the engine's
// runtime/test_font_data.cc into a Go file for dart:ui's text engine.
//
//	go run ./src/cmd/gentestfonts
package main

import (
	"bytes"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

const (
	source = "engine/src/flutter/runtime/test_font_data.cc"
	target = "engine/src/flutter/lib/ui/go/runtime_test_font_data.go"
)

func main() {
	src, err := os.ReadFile(source)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var out bytes.Buffer
	out.WriteString(`// Code generated by src/cmd/gentestfonts from engine/src/flutter/runtime/test_font_data.cc; DO NOT EDIT.

package ui

// The fonts flutter_tester registers with --use-test-fonts
// (runtime/test_font_data.cc's GetTestFontData and GetTestFontFamilyNames),
// in that order: every family that isn't one of them resolves to the first.
`)
	for _, f := range []struct{ array, name, goName string }{
		{"kFlutterTestFont", "FlutterTest", "testFontFlutterTest"},
		{"kAhemFont", "Ahem", "testFontAhem"},
		{"kCoughFont", "Cough", "testFontCough"},
	} {
		re := regexp.MustCompile(`(?s)static const unsigned char ` + f.array + `\[\] = \{(.*?)\};`)
		m := re.FindSubmatch(src)
		if m == nil {
			fmt.Fprintln(os.Stderr, "missing", f.array)
			os.Exit(1)
		}
		var data []byte
		for _, tok := range strings.FieldsFunc(string(m[1]), func(r rune) bool { return r == ',' || r == ' ' || r == '\n' }) {
			v, err := strconv.ParseUint(tok, 0, 8)
			if err != nil {
				fmt.Fprintln(os.Stderr, "bad byte", tok)
				os.Exit(1)
			}
			data = append(data, byte(v))
		}
		lre := regexp.MustCompile(`static const unsigned int ` + f.array + `Length = (\d+);`)
		lm := lre.FindSubmatch(src)
		if lm == nil {
			fmt.Fprintln(os.Stderr, "missing length of", f.array)
			os.Exit(1)
		}
		n, _ := strconv.Atoi(string(lm[1]))
		if n > len(data) {
			fmt.Fprintln(os.Stderr, "length mismatch for", f.array)
			os.Exit(1)
		}
		// GetTestFontData streams <array>Length bytes (kCoughFont's array
		// has 4 more).
		data = data[:n]
		fmt.Fprintf(&out, "\n// %s is %s (%d bytes).\nconst %s = \"", f.goName, f.array, len(data), f.goName)
		for i, b := range data {
			if i > 0 && i%32 == 0 {
				out.WriteString("\" +\n\t\"")
			}
			fmt.Fprintf(&out, "\\x%02x", b)
		}
		out.WriteString("\"\n")
	}
	out.WriteString(`
// testFontFamilyNames is GetTestFontFamilyNames.
var testFontFamilyNames = []string{"FlutterTest", "Ahem", "Cough"}

// testFontData is GetTestFontData.
var testFontData = []string{testFontFlutterTest, testFontAhem, testFontCough}
`)
	if err := os.WriteFile(target, out.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
