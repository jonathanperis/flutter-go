//go:build ignore

// gen writes table.go and unicode_grapheme_tests_data_test.go from
// package:characters 1.4.1's generated Dart sources:
//
//   - lib/src/grapheme_clusters/table.dart: the string literals _data,
//     _start, _stateMachine and _backStateMachine, decoded into their
//     UTF-16 code units, so the Go tables are the Dart ones bit for bit;
//
//   - test/src/unicode_grapheme_tests.dart: splitTests, emojis,
//     lowerChars and upperChars (the package's own test data).
//
//     go run gen.go [path/to/characters-1.4.1]
//
// (default: the pub cache's characters-1.4.1).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode/utf16"
	"unicode/utf8"

	"github.com/jonathanperis/flutter-go/src/dart"
)

func main() {
	root := filepath.Join(os.Getenv("HOME"), ".pub-cache/hosted/pub.dev/characters-1.4.1")
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	genTable(filepath.Join(root, "lib/src/grapheme_clusters/table.dart"))
	genTestData(filepath.Join(root, "test/src/unicode_grapheme_tests.dart"))
}

func read(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	return string(data)
}

func write(name string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(name, formatted, 0o644); err != nil {
		panic(err)
	}
}

func genTable(path string) {
	text := read(path)
	var out bytes.Buffer
	out.WriteString("// Code generated by gen.go from package:characters 1.4.1's\n" +
		"// lib/src/grapheme_clusters/table.dart. DO NOT EDIT.\n\npackage characters\n\n")
	for _, c := range []struct{ dart, goName string }{
		{"const String _data = ", "tableData"},
		{"const String _start = ", "tableStart"},
		{"const _stateMachine = ", "stateMachine"},
		{"const _backStateMachine = ", "backStateMachine"},
	} {
		i := strings.Index(text, c.dart)
		if i < 0 {
			panic("missing " + c.dart)
		}
		var units []uint16
		s := text[i+len(c.dart):]
		for {
			s = skipSpace(s)
			if s[0] == ';' {
				break
			}
			var lit []uint16
			lit, s = parseLiteral(s)
			units = append(units, lit...)
		}
		fmt.Fprintf(&out, "var %s = [...]uint16{", c.goName)
		for j, u := range units {
			if j%12 == 0 {
				out.WriteString("\n")
			}
			fmt.Fprintf(&out, "0x%04x, ", u)
		}
		out.WriteString("\n}\n\n")
	}
	write("table.go", out.Bytes())
}

func genTestData(path string) {
	text := read(path)
	var out bytes.Buffer
	out.WriteString("// Code generated by gen.go from package:characters 1.4.1's\n" +
		"// test/src/unicode_grapheme_tests.dart (Unicode's GraphemeBreakTest.txt and\n" +
		"// emoji-test.txt, under the Unicode license). DO NOT EDIT.\n\npackage characters\n\n")
	for _, c := range []struct{ dart, goName string }{
		{"const List<List<String>> splitTests = ", "splitTests"},
		{"const List<List<String>> emojis = ", "emojis"},
	} {
		i := strings.Index(text, c.dart)
		if i < 0 {
			panic("missing " + c.dart)
		}
		lists := parseListOfLists(text[i+len(c.dart):])
		fmt.Fprintf(&out, "var %s = [][]string{\n", c.goName)
		for _, l := range lists {
			out.WriteString("{")
			for _, s := range l {
				out.WriteString(strconv.Quote(dart.StringFromCharCodes(s)) + ", ")
			}
			out.WriteString("},\n")
		}
		out.WriteString("}\n\n")
	}
	for _, c := range []struct{ dart, goName string }{
		{"const lowerChars = <int>[", "lowerChars"},
		{"const upperChars = <int>[", "upperChars"},
	} {
		i := strings.Index(text, c.dart)
		if i < 0 {
			panic("missing " + c.dart)
		}
		body := text[i+len(c.dart):]
		body = body[:strings.Index(body, "]")]
		fmt.Fprintf(&out, "var %s = []int{", c.goName)
		for _, f := range strings.Split(body, ",") {
			f = strings.TrimSpace(f)
			if f == "" {
				continue
			}
			v, err := strconv.ParseInt(strings.Replace(f, "0x", "", 1), 16, 64)
			if err != nil {
				panic(err)
			}
			fmt.Fprintf(&out, "%d, ", v)
		}
		out.WriteString("}\n\n")
	}
	write("unicode_grapheme_tests_data_test.go", out.Bytes())
}

// skipSpace skips white space and // comments.
func skipSpace(s string) string {
	for {
		s = strings.TrimLeft(s, " \n\r\t")
		if strings.HasPrefix(s, "//") {
			s = s[strings.IndexByte(s, '\n'):]
			continue
		}
		return s
	}
}

// parseListOfLists parses a Dart list literal of lists of string literals.
func parseListOfLists(s string) [][][]uint16 {
	s = skipSpace(s)
	if s[0] != '[' {
		panic("expected [")
	}
	s = s[1:]
	var lists [][][]uint16
	for {
		s = skipSpace(s)
		switch s[0] {
		case ']':
			return lists
		case ',':
			s = s[1:]
			continue
		case '[':
			s = s[1:]
			var l [][]uint16
			for {
				s = skipSpace(s)
				if s[0] == ']' {
					s = s[1:]
					break
				}
				if s[0] == ',' {
					s = s[1:]
					continue
				}
				var lit []uint16
				lit, s = parseLiteral(s)
				l = append(l, lit)
			}
			lists = append(lists, l)
		default:
			panic("unexpected " + strconv.Quote(s[:20]))
		}
	}
}

// parseLiteral decodes one single-quoted Dart string literal (adjacent
// literals are concatenated by the callers).
func parseLiteral(s string) ([]uint16, string) {
	if s[0] != '\'' {
		panic("unexpected " + strconv.Quote(s[:20]))
	}
	var units []uint16
	i := 1
	for s[i] != '\'' {
		if s[i] != '\\' {
			r, size := utf8.DecodeRuneInString(s[i:])
			units = utf16.AppendRune(units, r)
			i += size
			continue
		}
		i++
		switch s[i] {
		case 'n':
			units = append(units, '\n')
		case 'r':
			units = append(units, '\r')
		case 'f':
			units = append(units, '\f')
		case 'b':
			units = append(units, '\b')
		case 't':
			units = append(units, '\t')
		case 'v':
			units = append(units, '\v')
		case 'x':
			v, err := strconv.ParseUint(s[i+1:i+3], 16, 16)
			if err != nil {
				panic(err)
			}
			units = append(units, uint16(v))
			i += 2
		case 'u':
			if s[i+1] == '{' {
				end := strings.IndexByte(s[i:], '}')
				v, err := strconv.ParseUint(s[i+2:i+end], 16, 32)
				if err != nil {
					panic(err)
				}
				if v > 0xFFFF {
					units = utf16.AppendRune(units, rune(v))
				} else {
					units = append(units, uint16(v))
				}
				i += end
			} else {
				v, err := strconv.ParseUint(s[i+1:i+5], 16, 16)
				if err != nil {
					panic(err)
				}
				units = append(units, uint16(v))
				i += 4
			}
		default: // \\, \', \", \$ and any other escaped character
			r, size := utf8.DecodeRuneInString(s[i:])
			units = utf16.AppendRune(units, r)
			i += size - 1
		}
		i++
	}
	return units, s[i+1:]
}
